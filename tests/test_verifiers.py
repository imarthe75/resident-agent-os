import tempfile
import unittest
from pathlib import Path

from verifiers import checks as c
from verifiers import run as runner


def tree(files):
    t = tempfile.TemporaryDirectory()
    root = Path(t.name)
    for rel, text in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    return t, root


class TestPkUuid(unittest.TestCase):
    def check(self, sql):
        t, root = tree({"db/a.sql": sql})
        self.addCleanup(t.cleanup)
        return c.pk_uuid(root)

    def test_uuid_pk_passes(self):
        r = self.check("CREATE TABLE IF NOT EXISTS app.t (id uuid NOT NULL DEFAULT uuidv7() PRIMARY KEY, n int);")
        self.assertEqual((r.status, r.checked), (c.CUMPLE, 1))

    def test_serial_bigint_identity_fail(self):
        r = self.check("""CREATE TABLE a (id serial PRIMARY KEY);
                          CREATE TABLE b (id bigint, n text, PRIMARY KEY (id));
                          CREATE TABLE c (id int GENERATED ALWAYS AS IDENTITY PRIMARY KEY);
                          CREATE TABLE d (id uuid GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY);""")
        self.assertEqual(r.status, c.NO_CUMPLE)
        self.assertEqual(len(r.detail), 4)

    def test_comments_do_not_count_and_no_sql_is_not_evaluated(self):
        r = self.check("-- CREATE TABLE x (id serial PRIMARY KEY);\nCREATE TABLE ok (id uuid PRIMARY KEY);")
        self.assertEqual(r.status, c.CUMPLE)
        t, root = tree({"readme.md": "no sql here"})
        self.addCleanup(t.cleanup)
        self.assertEqual(c.pk_uuid(root).status, c.NO_EVALUADO)           # nothing examined is never "CUMPLE"


class TestCompose(unittest.TestCase):
    def test_bind_under_data_passes_named_volume_fails(self):
        ok = "services:\n  db:\n    image: postgres:18\n    volumes:\n      - ./data/postgres:/var/lib/postgresql/data\n  app:\n    image: myapp\n"
        bad = "services:\n  db:\n    image: postgres:18\n    volumes:\n      - pgdata:/var/lib/postgresql/data\nvolumes:\n  pgdata:\n"
        for text, status in ((ok, c.CUMPLE), (bad, c.NO_CUMPLE)):
            t, root = tree({"docker-compose.yml": text})
            self.addCleanup(t.cleanup)
            r = c.compose_volumes(root)
            self.assertEqual((r.status, r.checked), (status, 1), r.detail)

    def test_no_stateful_service_is_not_evaluated(self):
        t, root = tree({"docker-compose.yml": "services:\n  web:\n    image: nginx:alpine\n"})
        self.addCleanup(t.cleanup)
        self.assertEqual(c.compose_volumes(root).status, c.NO_EVALUADO)

    def test_data_root_is_configurable(self):
        t, root = tree({"docker-compose.yml": "services:\n  r:\n    image: redis\n    volumes:\n      - /srv/state/redis:/data\n"})
        self.addCleanup(t.cleanup)
        self.assertEqual(c.compose_volumes(root, "/srv/state").status, c.CUMPLE)
        self.assertEqual(c.compose_volumes(root).status, c.NO_CUMPLE)


class TestAuditTriggers(unittest.TestCase):
    def test_declared_and_missing(self):
        sql = """CREATE TABLE a (id uuid PRIMARY KEY);
                 CREATE TABLE b (id uuid PRIMARY KEY);
                 CREATE TRIGGER a_audit_trg AFTER INSERT OR UPDATE ON app.a FOR EACH ROW EXECUTE FUNCTION auditoria.f();"""
        t, root = tree({"x.sql": sql})
        self.addCleanup(t.cleanup)
        r = c.audit_triggers(root)
        self.assertEqual(r.status, c.NO_CUMPLE)
        self.assertEqual(len(r.detail), 1)
        self.assertIn("'b'", r.detail[0])
        self.assertEqual(r.method, "heuristic")


class TestEndpointsAuth(unittest.TestCase):
    def test_fastapi_mutating_routes(self):
        code = ('@app.post("/a")\nasync def a(user=Depends(get_current_user)):\n    pass\n\n'
                '@app.delete("/b")\nasync def b():\n    pass\n\n@app.get("/open")\ndef c():\n    pass\n')
        t, root = tree({"api.py": code})
        self.addCleanup(t.cleanup)
        r = c.endpoints_auth(root)
        self.assertEqual((r.status, r.checked), (c.NO_CUMPLE, 2))
        self.assertEqual(len(r.detail), 1)
        self.assertIn("DELETE /b", r.detail[0])

    def test_other_frameworks_are_not_guessed(self):
        t, root = tree({"Ctrl.java": '@PostMapping("/x") public void x() {}'})
        self.addCleanup(t.cleanup)
        self.assertEqual(c.endpoints_auth(root).status, c.NO_EVALUADO)


class TestRunner(unittest.TestCase):
    def test_exit_codes(self):
        t, root = tree({"a.sql": "CREATE TABLE t (id serial PRIMARY KEY);"})
        self.addCleanup(t.cleanup)
        self.assertEqual(runner.main(["--path", str(root), "--only", "pk_uuid"]), 1)
        t2, root2 = tree({"readme": "x"})
        self.addCleanup(t2.cleanup)
        self.assertEqual(runner.main(["--path", str(root2), "--only", "pk_uuid"]), 0)      # NO_EVALUADO does not fail the run
        with self.assertRaises(SystemExit):
            runner.main(["--only", "nope"])


if __name__ == "__main__":
    unittest.main()
